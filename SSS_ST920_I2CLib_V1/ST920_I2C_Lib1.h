// Набор команд для графики
#define ST7920_CMD_BASIC            0x30  // Базовый режим (RE=0)
#define ST7920_CMD_EXTENDED         0x34  // Расширенный режим (RE=1)
#define ST7920_CMD_GFX_ON           0x36  // Расширенный режим + Графика (RE=1, G=1)
#define ST7920_CMD_CLS              0x01  // Очистка (только в Basic mode)

// Координатные маски
#define ST7920_Y_ADDR_BASE          0x80  // Базовый адрес Y (0-31)
#define ST7920_X_ADDR_BASE          0x80  // Базовый адрес X (0-7)
// -----------------------------------------------------------------------------
/**
 * Последовательность инициализации чистого графического режима:
 * 1. ST7920_CMD_BASIC    -> Выбор базы
 * 2. ST7920_CMD_CLS      -> Очистка DDRAM (на всякий случай)
 * 3. ST7920_CMD_EXTENDED -> Переход в расширенный режим
 * 4. ST7920_CMD_GFX_ON   -> Включение графики
 */

/*
  ЛОГИКА АДРЕСАЦИИ GDRAM:
  Экран 128x64 физически разделен на две части:
  Верхняя половина (Y: 0-31): X адреса 0x80..0x87 (8 слов по 16 бит)
  Нижняя половина  (Y: 32-63): X адреса 0x88..0x8F (те же 8 слов по 16 бит)

  Чтобы отправить слово (16 бит) по координатам X, Y:
  1. Если Y >= 32: Y_byte = 0x80 + (Y - 32), X_byte = 0x88 + X_word
  2. Если Y <  32: Y_byte = 0x80 + Y,        X_byte = 0x80 + X_word

  // Для любой строки y (0-63)
  uint8_t addr_y = 0x80 + (y % 32);
  uint8_t addr_x = (y < 32) ? 0x80 : 0x88;
  uint8_t *line_data = &fb[y * 16]; // 16 байт в строке (128 бит)
*/
// -----------------------------------------------------------------------------
// Макрос для вычисления байта адреса X с учетом половины экрана
#define ST7920_GET_X_ADDR(x_word, y) ((y < 32) ? (0x80 + x_word) : (0x88 + x_word))
// Макрос для вычисления байта адреса Y
#define ST7920_GET_Y_ADDR(y) (0x80 + (y % 32))
