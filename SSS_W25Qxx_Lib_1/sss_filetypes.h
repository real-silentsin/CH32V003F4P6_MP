// -----------------------------------------------------------------------------
#ifndef __SSS_FILETYPES__
// -----------------------------------------------------------------------------
#define __SSS_FILETYPES__
// -----------------------------------------------------------------------------
// 1. Определяем типы файлов (максимум 16 типов)
typedef enum {
    // Изображение (протокол)
    FILE_TYPE_IMAGEPROTO = 0,
    // Изображение (непрерывный)
    FILE_TYPE_IMAGECONT = 1,
    // Звуковой фрагмент (протокол)
    FILE_TYPE_SOUNDPROTO = 2,
    // Звуковой фрагмент (непрерывный)
    FILE_TYPE_SOUNDCONT = 3,
    // Бинарный набор данных
    FILE_TYPE_MISC = 4,
    // Малая иконка
    FILE_TYPE_ICON = 5,
    // Бинарное изображение для OLED
    FILE_TYPE_OLED_BIN_IMAGE = 6,
    // Действия с файлами
    FILE_TYPE_SYS_ACTION = 15
    // ... можно добавить до 16
} FileType_t;
// -----------------------------------------------------------------------------
// 2. Макросы для упаковки и распаковки ID
// Выделяем 4 старших бита под тип (0...15), 12 младших — под номер (0...4095)
#define MAKE_FILE_ID(type, num) (uint16_t)((((type) & 0x0F) << 12) | ((num) & 0x0FFF))
#define GET_FILE_TYPE(file_id) (uint8_t)(((file_id) >> 12) & 0x0F)
#define GET_FILE_NUM(file_id) (uint16_t)((file_id) & 0x0FFF)
// -----------------------------------------------------------------------------
#endif
