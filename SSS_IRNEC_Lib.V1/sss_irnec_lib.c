// -----------------------------------------------------------------------------
#define T0_W4START       0  // Ожидание начала передачи стартового импульса (A)
#define T0_W4FPAUSE      2  // Измерение первой паузы (B)

#define DATA_W42START    3  // Ожидание окончания импульса передачи данных (C)
#define DATA_W42END      4  // Ожидание окончания паузы передачи данных (D)
// -----------------------------------------------------------------------------
volatile uint8_t curr_cycle = T0_W4START;
// -----------------------------------------------------------------------------
// 1 байт - адрес
// 2 байт - инверсный адрес или второй байт адреса при расширенном протоколе
// 3 байт - команда
// 4 байт - инверсная команда
uint8_t ir_data[4] = { 0, 0, 0, 0 };
uint8_t ir_last[4] = { 0, 0, 0, 0 };
// -----------------------------------------------------------------------------
volatile IR_DataReady_Type dataready = IRDR_NO;
volatile uint8_t data_counter = 0;
// -----------------------------------------------------------------------------
// Инициализация линий и прерываний для работы протокола IR NEC
void IR_Init(void) {
    // -------------------------------------------------------------------------
    GPIO_InitTypeDef GPIO_InitStructure = {0};
    EXTI_InitTypeDef EXTI_InitStructure = {0};
    NVIC_InitTypeDef NVIC_InitStructure = {0};
    // -------------------------------------------------------------------------
    // Включение порта
    RCC_APB2PeriphClockCmd (IR_NEC_PORT.rcc, ENABLE);
    // -------------------------------------------------------------------------
    // Инициализация порта линии IR_IN
    GPIO_InitStructure.GPIO_Pin = IR_NEC_PORT.pin;
    GPIO_InitStructure.GPIO_Mode = GPIO_Mode_IN_FLOATING;
    GPIO_InitStructure.GPIO_Speed = GPIO_Speed_50MHz;
    GPIO_Init (IR_NEC_PORT.port, &GPIO_InitStructure);
    // -------------------------------------------------------------------------
    // Инициализация прерывания линии IR_IN
    /* GPIOx ----> IR_IN_EXTI_LINE */
    GPIO_EXTILineConfig (IR_NEC_PORT.exti_port_src, IR_NEC_PORT.exti_pin_src);
    EXTI_InitStructure.EXTI_Line = IR_NEC_PORT.exti_line;
    EXTI_InitStructure.EXTI_Mode = EXTI_Mode_Interrupt;
    EXTI_InitStructure.EXTI_Trigger = EXTI_Trigger_Rising_Falling;
    EXTI_InitStructure.EXTI_LineCmd = ENABLE;
    EXTI_Init (&EXTI_InitStructure);
    // -------------------------------------------------------------------------
    // Регистрируем канал прерывания в контроллере прерываний
    /* IR_IN_EXTI_LINE ----> EXTI7_0_IRQn */
    NVIC_InitStructure.NVIC_IRQChannel = EXTI7_0_IRQn;
    NVIC_InitStructure.NVIC_IRQChannelPreemptionPriority = 0;
    NVIC_InitStructure.NVIC_IRQChannelSubPriority = 1;
    NVIC_InitStructure.NVIC_IRQChannelCmd = ENABLE;
    NVIC_Init (&NVIC_InitStructure);
    // -------------------------------------------------------------------------
    // Инициализация таймера - счетчика микросекунд
    SysTimer1_Init();
    // -------------------------------------------------------------------------
}
// -----------------------------------------------------------------------------
/**
 * Проверяет, входит ли значение в диапазон +/- 20% от целевого.
 * @param value  - измеряемое значение (например, TIM2->CNT)
 * @param target - эталонное значение
 * @return 1 если в диапазоне, 0 если нет
 */
uint8_t Is_In_Range_10(uint16_t value, uint16_t target) {
    
    // Вычисляем отклонение (20% = target / 5)
    uint16_t tolerance = target / 5;
    
    uint16_t min_val = target - tolerance;
    uint16_t max_val = target + tolerance;

    // Проверка границ
    if (value >= min_val && value <= max_val) {
        return 1;
    }

    return 0;
}
// -----------------------------------------------------------------------------
// Чтение состояния порта IR IN
uint8_t IRSENSOR() {

    return (GPIO_ReadInputDataBit (IR_NEC_PORT.port, IR_NEC_PORT.pin));
}
// -----------------------------------------------------------------------------
// Полный сброс состояния приемника
void IR_FullReset(void) {

    curr_cycle = T0_W4START;
    dataready = IRDR_NO;
    data_counter = 0;

    ir_data[0] = 0;
    ir_data[1] = 0;
    ir_data[2] = 0;
    ir_data[3] = 0;
}
// -----------------------------------------------------------------------------
// Метод декодирования протокола IR NEC, работает в связке с прерываниями
void IR_NEC_PROC(void) {
    // -------------------------------------------------------------------------
    // Длина пакета IR NEC = 67,5 мСек
    // -------------------------------------------------------------------------
    // Получаем значение длительности импульса с момента старта
    uint32_t pulse_width = SysTimer1_GetUs();
    // -------------------------------------------------------------------------
    if (curr_cycle == T0_W4START) {

        // Поиск стартового импульса 9 мСек
        if (Is_In_Range_10(pulse_width, 9000)) {
            
            curr_cycle = T0_W4FPAUSE;
        }

        return;
    }
    // -------------------------------------------------------------------------
    // Ожидание окончания паузы после стартового пакета
    // -------------------------------------------------------------------------
    if (curr_cycle == T0_W4FPAUSE) {

        // REPEAT
        if (Is_In_Range_10(pulse_width, 2250)) {

            IR_FullReset();
            dataready = IRDR_REPEAT;

            return;
        }

        // DATA
        if (Is_In_Range_10(pulse_width, 4500)) {

            IR_FullReset();
            curr_cycle = DATA_W42START;

            return;
        }

        curr_cycle = T0_W4START;
        return;
    }
    // -------------------------------------------------------------------------
    // Ожидание окончания импульса данных (C)
    // -------------------------------------------------------------------------
    if (curr_cycle == DATA_W42START) {

        // Ожидание импульса 560 мкСек
        if (Is_In_Range_10(pulse_width, 560)) {
            
            curr_cycle = DATA_W42END;
        }

        return;
    }
    // -------------------------------------------------------------------------
    // Ожидание окончания импульса данных (D)
    // -------------------------------------------------------------------------
    if (curr_cycle == DATA_W42END) {

        if (IRSENSOR() == 0 && data_counter < 32) {

            uint8_t bit_data = 2;

            // 560 uS
            if (Is_In_Range_10(pulse_width, 560)) {

                bit_data = 0;
            }

            // 1690 uS
            if (Is_In_Range_10(pulse_width, 1690)) {

                bit_data = 1;
            }

            if (bit_data < 2) {

                if (bit_data == 1) {

                    //sbi(ir_data[addr_index], addr_bit_index);
                    ir_data[data_counter / 8] |= (1 << (data_counter % 8));
                }

                data_counter++;
            }
        }

        // Получение данных завершено?
        if (data_counter == 32) {

            // Проверка данных на корректность...
            ir_data[3] = ~ir_data[3];
            // Адрес передается без изменений, а второй байт команды инвертируется...

            if (ir_data[2] == ir_data[3]) {

                // Если первый байт команды равен инвертированному второму, значит успех!
                dataready = IRDR_READY;

                // Сохранение текущего состояния (для ситуации REPEAT)
                ir_last[0] = ir_data[0];
                ir_last[1] = ir_data[1];
                ir_last[2] = ir_data[2];
                ir_last[3] = ir_data[3];
            } else {

                dataready = IRDR_NO;
            }

            data_counter = 0;
            curr_cycle = T0_W4START;

            return;
        }

        curr_cycle = DATA_W42START;
    }
    // -------------------------------------------------------------------------
}
// -----------------------------------------------------------------------------
// Получение данных из буфера приема [0..3]
uint8_t IR_GetData(uint8_t index) {

    return (index < 4) ? ir_data[index] : 0;
}
// -----------------------------------------------------------------------------
// Получение предыдущих данных из буфера приема [0..3]
uint8_t IR_GetLastData(uint8_t index) {

    return (index < 4) ? ir_last[index] : 0;
}
// -----------------------------------------------------------------------------
// Получение текущего статуса
IR_DataReady_Type IR_GetStatus() {

    return dataready;
}
// -----------------------------------------------------------------------------
// Сброс статуса
void IR_ResetStatus() {

    dataready = IRDR_NO;
}
