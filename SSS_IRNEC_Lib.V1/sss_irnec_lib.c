 // -----------------------------------------------------------------------------
 // Обработка прерывания от порта IR_IN
void EXTI7_0_IRQHandler(void) {
    // -------------------------------------------------------------------------
    if (EXTI_GetITStatus (IR_NEC_PORT.exti_line) != RESET) {
        // ---------------------------------------------------------------------
        // Временно маскируем прерывания по линии IR_IN (IR_IN_EXTI_LINE)
        EXTI->INTENR &= ~IR_NEC_PORT.exti_line;
        // ---------------------------------------------------------------------
        // Если таймер не запущен или остановился при переполнении...
        if (!SysTimer1_IsRunning()) { IR_FullReset(); }
        // ---------------------------------------------------------------------
        // Длина пакета IR NEC = 67,5 мСек
        IR_NEC_PROC();
        // ---------------------------------------------------------------------
        // Сброс таймера и запуск его заново
        SysTimer1_Start(TIMER_MAX_COUNT);
        // ---------------------------------------------------------------------
        // Сбрасываем флаг признака прерывания
        EXTI_ClearITPendingBit (IR_NEC_PORT.exti_line);
        // ---------------------------------------------------------------------
        // Разрешаем прерывания по линии IR_IN
        EXTI->INTENR |= IR_NEC_PORT.exti_line;
        // ---------------------------------------------------------------------
    }
    // -------------------------------------------------------------------------
}
