#include "ch32v00x.h"
#include "sss_qucr_lib.h"
// -----------------------------------------------------------------------------
// Конфигурация системы на внешний кварц
QUCR_SYS_SRC_Types RCC_HSE_Configuration () {
    // -------------------------------------------------------------------------
    // Сброс системы тактирования
    RCC_DeInit();
    // -------------------------------------------------------------------------
    // 1. Включаем внешний кварц (HSE)
    RCC_HSEConfig (RCC_HSE_ON);
    // -------------------------------------------------------------------------
    if (RCC_WaitForHSEStartUp() == READY) {
        // ---------------------------------------------------------------------
        // 2. Настройка Flash Latency
#if defined(QUCR_FREQ_24) || defined(QUCR_FREQ_20) || defined(QUCR_FREQ_16)
        FLASH_SetLatency (FLASH_Latency_1);
#endif
#if defined(QUCR_FREQ_12)
        FLASH_SetLatency (FLASH_Latency_0);
#endif
        // ---------------------------------------------------------------------
        // 3. Настройка делителей
        RCC_HCLKConfig (RCC_SYSCLK_Div1);  // HCLK = 40MHz
        // ---------------------------------------------------------------------
#ifdef QUCR_USE_PLL
        // 4. Настройка PLL: Частота кварца * 2
        // В CH32V003 PLLSource_HSE по умолчанию использует входную частоту напрямую
        RCC_PLLConfig (RCC_PLLSource_HSE_MUL2);
        // -----------------------------------------------------------------
        // 5. Запуск PLL
        RCC_PLLCmd (ENABLE);
        while (RCC_GetFlagStatus (RCC_FLAG_PLLRDY) == RESET);
        // -----------------------------------------------------------------
        // 6. Переключение на PLL
        RCC_SYSCLKConfig (RCC_SYSCLKSource_PLLCLK);
        // -----------------------------------------------------------------
        // Ждем подтверждения переключения (0x08 - PLL источник)
        while (RCC_GetSYSCLKSource() != 0x08) { }
        // -----------------------------------------------------------------
#else
        // -----------------------------------------------------------------
        // Выбираем HSE как источник системного тактирования
        RCC_SYSCLKConfig(RCC_SYSCLKSource_HSE);
        // -----------------------------------------------------------------
        // Ждем, пока HSE станет активным источником
        while (RCC_GetSYSCLKSource() != 0x04);
        // -----------------------------------------------------------------
#endif
    } else {
    // ---------------------------------------------------------------------
        // Ошибка запуска кварца — можно переключиться на внутренний HSI
        /* --- ОШИБКА: Кварц не ответил, остаемся на HSI (24 МГц) --- */
        RCC_HSEConfig (RCC_HSE_OFF);  // Выключаем неисправный кварц
        // ---------------------------------------------------------------------
        // Для 24 МГц (HSI) Latency можно оставить 0 или поставить 1 для стабильности
        FLASH_SetLatency (FLASH_Latency_1);
        // ---------------------------------------------------------------------
        RCC_HCLKConfig (RCC_SYSCLK_Div1);
        RCC_SYSCLKConfig (RCC_SYSCLKSource_HSI);
        // ---------------------------------------------------------------------
        while (RCC_GetSYSCLKSource() != 0x00);
        // ---------------------------------------------------------------------
    }
    // -------------------------------------------------------------------------
    // Обновляем глобальную переменную частоты для работы Delay_Ms()
    SystemCoreClockUpdate();
    // -------------------------------------------------------------------------
    // Повторное определение текущего источника тактирования MCU
    switch (RCC_GetSYSCLKSource()) {

    case 0x08: return QUCR_SYSSRC_PLL;
    case 0x04: return QUCR_SYSSRC_HSE;

    default: return QUCR_SYSSRC_HSI;
    }
    // -------------------------------------------------------------------------
}
