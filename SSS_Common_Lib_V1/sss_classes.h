/* Макросы для битовых операций */
// -----------------------------------------------------------------------------
// Очистка или установка бита (по ИНДЕКСУ бита)
#define sbi(b, idx) ((b) |= (1UL << (idx)))
#define cbi(b, idx) ((b) &= ~(1UL << (idx)))
// -----------------------------------------------------------------------------
/* Для работы по ИНДЕКСУ бита */
#define is_set_idx(b, idx) (((b) & (1UL << (idx))) != 0)
#define is_clear_idx(b, idx) (((b) & (1UL << (idx))) == 0)
// -----------------------------------------------------------------------------
/* Для работы по МАСКЕ ( (1<<4), 0x10, и т.д. ) */
#define is_set_mask(val, mask) (((val) & (mask)) != 0)
#define is_clear_mask(val, mask) (((val) & (mask)) == 0)
