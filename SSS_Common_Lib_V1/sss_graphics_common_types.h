// -----------------------------------------------------------------------------
#ifndef __SSS_MATRIX200CT__
// -----------------------------------------------------------------------------
#define __SSS_MATRIX200CT__
// -----------------------------------------------------------------------------
// Структура, представляющая герметрические точки
typedef struct _Point {
    int16_t X;
    int16_t Y;
    int16_t extend;
} Point;
// -----------------------------------------------------------------------------
// Структура, представляющая герметрические размеры
typedef struct _Size {
    uint16_t Width;
    uint16_t Height;
} Size;
// -----------------------------------------------------------------------------
// Структура, представляющая прямоугольную область
typedef struct _Rect {
    Point Location;
    Size ClientSize;
} Rect;
// -----------------------------------------------------------------------------
// Указатель на один из углов области
typedef enum _Corner {
    TopLeft,
    BottomLeft,
    TopRight,
    BottomRight
} Corner;
// -----------------------------------------------------------------------------
// Направление печати ля стандартной функции печати
typedef enum {
    WS_Horizonlal,
    WS_Vertical
} WriteString_DirectionType;
// -----------------------------------------------------------------------------
typedef enum {
    WM_None = 0,
    WM_Full = 1
} WriteString_WrapMode;
// -----------------------------------------------------------------------------
typedef enum {
    WA_Center = 0,
    WA_Left = 1,
    WA_Right = 2
} WriteString_Align;
// -----------------------------------------------------------------------------
// Структуры для шрифтов GFX
// -----------------------------------------------------------------------------
typedef struct {
    uint16_t bitmapOffset;  // Смещение в массиве битмапов
    uint8_t width;          // Ширина символа в пикселях
    uint8_t height;         // Высота символа
    uint8_t xAdvance;       // На сколько сдвинуть курсор по X
    int8_t xOffset;         // Смещение по X относительно курсора
    int8_t yOffset;         // Смещение по Y (обычно отрицательное)
} GFXglyph;

// -----------------------------------------------------------------------------
typedef struct {
    uint8_t *bitmap;   // Массив всех битмапов
    GFXglyph *glyph;   // Массив описаний глифов
    uint8_t first;     // ASCII код первого символа (обычно 0x20)
    uint8_t last;      // ASCII код последнего символа
    uint8_t yAdvance;  // Высота строки
} GFXfont;
// -----------------------------------------------------------------------------
typedef struct {
    const uint8_t *data;   // Указатель на начало массива (FONT_7SEG_IMAGES)
    uint16_t glyph_size;   // Размер одного символа в байтах (например, 240)
    uint8_t width;         // Ширина символа (32)
    uint8_t height;        // Высота символа (50)
    uint16_t total_chars;  // Общее количество символов в массиве
} BINFont;
// -----------------------------------------------------------------------------
// Стили для отображения символов (OLED)
#define SYMSTYLE_NORM           0x00        // Нормальное представление
#define SYMSTYLE_INV            (1 << 0)    // Бит 0 - Инверсия символа
#define SYMSTYLE_UL             (1 << 1)    // Бит 1 - Нижнее подчеркивание
#define SYMSTYLE_DL             (1 << 2)    // Бит 2 - Верхнее подчеркивание
#define SYMSTYLE_NOALIGN        (1 << 3)    // Бит 3 - Не выравнивать содержимое
#define SYMSTYLE_WIDE           (1 << 4)    // Бит 4 - Удвоение символа (WIDE 16x16)
#define SYMSTYLE_LED            (1 << 5)    // Бит 5 - "LED" символ (из двух символов)
#define SYMSTYLE_WIDTHLED       (1 << 6)    // Бит 6 - широкий "LED" символ (из двух символов)
#define SYMSTYLE_QUAD           (1 << 7)    // Бит 7 - символ 32x32 (три знакоместа)
#define SYMSTYLE_QUADICON       (1 << 8)    // Бит 8 - иконка 32x32 (четыре знакоместа)
#define SYMSTYLE_NOCYR          (1 << 9)    // Бит 9 - запрет интерпретации кириллицы
// -----------------------------------------------------------------------------
#endif
