// Внимание! Обращение к методу сбрасывает код ошибки к норме.
uint32_t DAC_getLastError() {

    uint32_t tmp_err = dac_last_error;
    dac_last_error = I2C_ERROR_SUCCESS;

    return tmp_err;
}
// -----------------------------------------------------------------------------
// Инициализация логики
// Подразумевается, что аппаратный механизм I2C был уже настроен!
void DAC_Init(uint8_t chip_number, uint8_t zero_start) { 

#ifdef DAC_USE_I2C_INITIALIZATION
    IIC_Init(DAC_I2C_SPEED, I2C_SELF_ADDRESS);
#endif

    if (zero_start > 0) {
    
        DAC_FastWrite(chip_number, 0);
    }
}
// -----------------------------------------------------------------------------
// Создание адреса из физического адреса устройства и номера чипа (A0)
uint8_t DAC_GetAddress(uint8_t chip_number) {
    
    uint8_t ack_temp = ((chip_number & 0x01) << 1);
    
    return (HA_MCP4725 | ack_temp);
}
// -----------------------------------------------------------------------------
// Ввод произвольного адреса
// chip_number  - номер чипа на шине (A0)
// mode         - режим (0 - запись, 1 - чтение)
// Выход: 0 - успешно, 1 - сбой
uint8_t DAC_SetHeader(uint8_t chip_number, uint8_t mode) {
    // -------------------------------------------------------------------------
    uint8_t dac_address = DAC_GetAddress(chip_number);
    // -------------------------------------------------------------------------
    /* switch (mode) {
        
        case 1:            
            sbi(dac_address, 0);
            break;
            
        default:
            cbi(dac_address, 0);
            break;
    } */
    // -------------------------------------------------------------------------
    dac_last_error = i2c_begin_transaction(dac_address, mode);

    return dac_last_error;
    // -------------------------------------------------------------------------
}
// -----------------------------------------------------------------------------
// Установка режима POWER-DOWN
void DAC_SetPDM(uint8_t value) {
    
    pdm_register = (value & 0x03);
}
// -----------------------------------------------------------------------------
// Чтение установок режима POWER-DOWN
uint8_t DAC_GetPDM() {
    
    return (pdm_register & 0x03);
}
// -----------------------------------------------------------------------------
// Быстрая запись в регистр DAC
uint32_t DAC_FastWrite(uint8_t chip_number, uint16_t out_voltage) {
    // -------------------------------------------------------------------------
    dac_last_error = DAC_SetHeader(chip_number, I2C_Direction_Transmitter);
    // -------------------------------------------------------------------------
    if (dac_last_error != I2C_ERROR_SUCCESS) {

        // Заканчиваем цикл передачи данных
        I2C_GenerateSTOP( I2C1, ENABLE );
        
        return dac_last_error;
    }
    // -------------------------------------------------------------------------
    uint8_t hi_byte = ((out_voltage >> 8) & 0x0F);
    hi_byte |= ((pdm_register & 0x03) << 4);
    
    uint8_t lo_byte = out_voltage;
    // -------------------------------------------------------------------------
    dac_last_error = i2c_send_byte(hi_byte);
    // -------------------------------------------------------------------------
    if (dac_last_error != I2C_ERROR_SUCCESS) {

        // Заканчиваем цикл передачи данных
        I2C_GenerateSTOP( I2C1, ENABLE );
        
        return dac_last_error;
    }
    // -------------------------------------------------------------------------
    dac_last_error = i2c_send_byte(lo_byte);
    // -------------------------------------------------------------------------
    // Заканчиваем цикл передачи данных
    I2C_GenerateSTOP( I2C1, ENABLE );
    // -------------------------------------------------------------------------
    return dac_last_error;
    // -------------------------------------------------------------------------    
}
// -----------------------------------------------------------------------------
// Чтение данных из БИС DAC в буфер (5 байт) - настройки DAC
uint8_t DAC_OptionsRead(uint8_t chip_number) {
    // -------------------------------------------------------------------------
    dac_last_error = DAC_SetHeader(chip_number, I2C_Direction_Receiver);
    // -------------------------------------------------------------------------
    if (dac_last_error != I2C_ERROR_SUCCESS) {

        // Заканчиваем цикл передачи данных
        I2C_GenerateSTOP( I2C1, ENABLE );
        
        return dac_last_error;
    }
    // -------------------------------------------------------------------------
    // Первые три байта - текущие настройки DAC
    // Байт 0: [Ready|POR|0|0|0|PD1|PD0|0]
    // Байт 1: [D11|D10|D9|D8|D7|D6|D5|D4]
    // Байт 2: [D3|D2|D1|D0|X|X|X|X]
    // Настройки EEPROM (следующие два байта)
    // Байт 4: [X|PD1|PD0|X|D11|D10|D9|D8]
    // Байт 5: [D7|D6|D5|D4|D3|D2|D1|D0]
    // -------------------------------------------------------------------------
    // Для 3 байт:
    for (int index = 0; index < 5; index++) {

        // Если следующий байт — последний
        // Сбрасываем ACK заранее!
        if (index == 3) { i2c_setNACK(); }

        dac_data[index] = i2c_read_byte_simple();
    }
    // -------------------------------------------------------------------------
    // Заканчиваем цикл передачи данных
    I2C_GenerateSTOP (I2C1, ENABLE);
    // -------------------------------------------------------------------------
    // Перед выходом из функции ВСЕГДА возвращайте ACK в дефолт, 
    // иначе следующее чтение (даже другого устройства) начнется с NACK.
    i2c_setACK();
    // -------------------------------------------------------------------------
    return dac_last_error;
    // -------------------------------------------------------------------------    
}
// -----------------------------------------------------------------------------
// Проверка готовности DAC к обмену
// Выход: 1 - готов к обмену, 0 - не готов к обмену
uint8_t DAC_isReady(uint8_t chip_number) {

    if (I2C_ERROR_SUCCESS == DAC_OptionsRead(chip_number)) {

        if ((dac_data[0] & 0x80) > 0) { return 1; }
    }

    return 0;
}
// -----------------------------------------------------------------------------
// Получение настройки DAC для указанного выходного напряжения в mV
// Входное значение от нуля до U_REF_VALUE в милливольтах
// вход: out_mV - [0..(mv)U_REF_VALUE]
// выход: значение, записываемое в DAC [0..4095]
uint16_t DAC_GetValue(uint16_t out_mV) {
    
    // Учитываем коррекцию
    uint32_t target_mv = out_mV + U_OUT_CORRECT;
    
    // Проверка на переполнение сверху
    if (target_mv >= U_REF_VALUE) { return 4095; }
    
    // Считаем с округлением: (V * 4095 + Vref/2) / Vref
    uint32_t result = (target_mv * 4095l) + (U_REF_VALUE / 2);

    return (uint16_t)(result / U_REF_VALUE);
}
// -----------------------------------------------------------------------------
// Получение настройки DAC для указанного выходного напряжения, превышающего питание DAC
// Входное значение от нуля до HARDWARE_VOLTAGE_MAX в милливольтах
// вход: out_mV - [0..(mv)HARDWARE_VOLTAGE_MAX]
// выход: значение, записываемое в DAC [0..4095]
uint16_t DAC_GetVoltage(uint16_t value_mv) {

    if (value_mv > HARDWARE_VOLTAGE_MAX) value_mv = HARDWARE_VOLTAGE_MAX;

    // 1. Добавляем коррекцию (приведенную к масштабу выхода)
    // Либо используй U_OUT_CORRECT напрямую, если она в единицах выхода
    uint32_t corrected_mv = value_mv + (U_OUT_CORRECT * HARDWARE_VOLTAGE_MAX / U_REF_VALUE);

    // 2. Считаем сразу значение для ЦАП (через float для максимальной точности)
    // Формула: (Цель / Макс_Выход) * 4095
    float dac_raw = ((float)corrected_mv * 4095.0f) / (float)HARDWARE_VOLTAGE_MAX;

    // 3. Округляем по правилам математики (+0.5) и ограничиваем
    if (dac_raw > 4095.0f) dac_raw = 4095.0f;
    uint16_t dac_value_realm = (uint16_t)(dac_raw + 0.5f);

    return dac_value_realm;
    //DAC_FastWrite(0, dac_value_realm);
}
