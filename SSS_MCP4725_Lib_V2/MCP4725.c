uint32_t dac_last_error = 0;
// -----------------------------------------------------------------------------
// Настройки POWER-DOWN режима
uint8_t pdm_register = PDM_NORMAL;
// -----------------------------------------------------------------------------
// Сырые данные из DAC
uint8_t dac_data[5] = { 0, 0, 0, 0, 0 };
// -----------------------------------------------------------------------------
// Физический адрес устройства [A0, A1, A2] по пинам
// uint8_t device_phy_addr = 0;
// -----------------------------------------------------------------------------
