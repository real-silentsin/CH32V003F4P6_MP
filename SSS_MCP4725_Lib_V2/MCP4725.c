// Полный цикл записи в БИС DAC
uint32_t DAC_Write(uint8_t chip_number, uint16_t out_voltage, uint8_t eeprom_enabled) {
    // -------------------------------------------------------------------------
    dac_last_error = DAC_SetHeader(chip_number, I2C_Direction_Transmitter);
    // -------------------------------------------------------------------------
    if (dac_last_error != I2C_ERROR_SUCCESS) {

        // Заканчиваем цикл передачи данных
        I2C_GenerateSTOP( I2C1, ENABLE );
        
        return dac_last_error;
    }
    // -------------------------------------------------------------------------
    // Формирование второго байта заголовка (см. datasheet p.19)
    uint8_t sub_header = (eeprom_enabled > 0) ? DAC_WRITE_DAC_EPR : DAC_WRITE_DAC;
    sub_header |= (pdm_register << 1);
    // -------------------------------------------------------------------------
    // Отправка второго байта заголовка
    dac_last_error = i2c_send_byte(sub_header);
    // -------------------------------------------------------------------------
    if (dac_last_error != I2C_ERROR_SUCCESS) {

        // Заканчиваем цикл передачи данных
        I2C_GenerateSTOP( I2C1, ENABLE );
        
        return dac_last_error;
    }
    // -------------------------------------------------------------------------
    uint8_t hi_byte = (out_voltage >> 4);          // Сдвиг на 4: берем верхние 8 бит (D11-D4)
    uint8_t lo_byte = (out_voltage << 4) & 0xF0;   // Сдвиг влево: нижние 4 бита (D3-D0) уходят в начало байта
    // -------------------------------------------------------------------------
    dac_last_error = i2c_send_byte(hi_byte);
    // -------------------------------------------------------------------------
    if (dac_last_error != I2C_ERROR_SUCCESS) {

        // Заканчиваем цикл передачи данных
        I2C_GenerateSTOP( I2C1, ENABLE );
        
        return dac_last_error;
    }
    // -------------------------------------------------------------------------
    dac_last_error = i2c_send_byte(lo_byte);
    // -------------------------------------------------------------------------
    // ЗАВЕРШАЕМ транзакцию ПЕРЕД проверкой готовности
    I2C_GenerateSTOP(I2C1, ENABLE);
    // -------------------------------------------------------------------------
    // Если писали в EEPROM — ждем завершения (около 30-50мс)
    if (eeprom_enabled) {

        uint32_t eeprom_timeout = 100;

        while (DAC_isReady (chip_number) == 0) {

            Delay_Ms (1);  // Ждем по 1 мс

            if (eeprom_timeout-- == 0) {
                dac_last_error = I2C_ERROR_TIME_OUT;
                break;
            }
        }
    }
    // -------------------------------------------------------------------------
    return dac_last_error;
    // -------------------------------------------------------------------------
}
// -----------------------------------------------------------------------------
// Программирование DAC на "тихий запуск" - 1k на "землю" и ноль на выходе
// Один раз для одного DAC.
void DAC_SetMainMode(uint8_t chip_number) {

    DAC_SetPDM(PDM_1K2GND);
    DAC_Write(chip_number, 0, 1);
    DAC_SetPDM(PDM_NORMAL);
}
