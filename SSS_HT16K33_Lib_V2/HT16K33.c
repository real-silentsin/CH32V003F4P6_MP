// Отсылка символа в указанное знакоместо
void HT16K33_Send(uint8_t chip_number, uint8_t place, uint8_t value) {
    
    uint8_t _value = value;
    uint8_t _dp = 0;
    
    if (is_set_idx(value, 7)) {
        
        _dp = 1;
        cbi(_value, 7);
    }
    
    uint8_t data = _symbol[_value];
   
    if (_dp == 1) { sbi(data, HT_DP_BIT); }
    
    // Перекодирование номеров знакомест в зависимости от реального подключения
    HT16K33_Write(chip_number, HT_DIGITS_ADDRESS[place], data);
    //HT16K33_Write(chip_number, place, data);
}
